<script lang="ts">
	import { browser } from '$app/environment';
	import { i18n } from '$lib/stores/i18n.svelte';
	import LangSwitcher from '$lib/components/LangSwitcher.svelte';
	import Seo from '$lib/components/Seo.svelte';
	import { resolveMethod } from '$lib/content/methodology';

	let { data } = $props();
	const title = $derived(i18n.t(data.titleKey));
	const description = $derived(data.descKey ? i18n.t(data.descKey) : null);
	const locale = $derived(i18n.locale);
	const method = $derived(resolveMethod(data.content.method, locale));
	// label for the page title in the route's language (gn keeps the Spanish loanword)
	const METOD = { es: ['Metodología', 'Metodología del análisis'], gn: ['Metodología', 'Metodología del análisis'],
		en: ['Methodology', 'Methodology of the analysis'], pt: ['Metodologia', 'Metodologia da análise'] } as const;
	const metod = $derived(METOD[(locale as keyof typeof METOD)] ?? METOD.es);

	// Two-scale layers: per-territory ranges of the provincial scale + share of
	// hexagons per band (generated by pipeline/build_pm25_scale_stats.py).
	const SCALE_TXT = {
		es: { h: 'Escalas de color por provincia, departamento y estado', terr: 'Provincia, departamento o estado', range: 'Escala provincial (P2–P98)', minmax: 'Mín–máx', bands: '% de hexágonos por banda OMS 2021 (µg/m³)',
			intro: (lo: string, hi: string) => `El mapa ofrece dos escalas. <b>Provincial</b> (por defecto): los colores van del percentil 2 al 98 de la provincia, el departamento paraguayo o el estado brasileño abierto — es la unidad de gobierno, y la escala muestra dónde está peor dentro de ella; los colores no se comparan de una unidad a otra. <b>Regional</b>: rango fijo de ${lo} a ${hi} µg/m³ en Argentina, Paraguay y Brasil — el mismo color es el mismo valor. La tabla da el rango de la escala provincial de cada provincia, departamento y estado y el reparto de sus hexágonos en las bandas de la OMS.` },
		en: { h: 'Colour scales by province, department and state', terr: 'Province, department or state', range: 'Provincial scale (P2–P98)', minmax: 'Min–max', bands: '% of hexagons per WHO 2021 band (µg/m³)',
			intro: (lo: string, hi: string) => `The map offers two scales. <b>Provincial</b> (default): colours run from the 2nd to the 98th percentile of the open province, Paraguayan department or Brazilian state — the governing unit — and the scale shows where it is worse within it; colours are not comparable from one unit to another. <b>Regional</b>: a fixed ${lo}–${hi} µg/m³ range across Argentina, Paraguay and Brazil — the same colour is the same value. The table gives the provincial-scale range of each province, department and state and how its hexagons fall into the WHO bands.` },
		pt: { h: 'Escalas de cor por província, departamento e estado', terr: 'Província, departamento ou estado', range: 'Escala provincial (P2–P98)', minmax: 'Mín–máx', bands: '% de hexágonos por faixa OMS 2021 (µg/m³)',
			intro: (lo: string, hi: string) => `O mapa oferece duas escalas. <b>Provincial</b> (padrão): as cores vão do percentil 2 ao 98 da província, do departamento paraguaio ou do estado brasileiro aberto — é a unidade de governo, e a escala mostra onde está pior dentro dela; as cores não se comparam de uma unidade a outra. <b>Regional</b>: faixa fixa de ${lo} a ${hi} µg/m³ na Argentina, no Paraguai e no Brasil — a mesma cor é o mesmo valor. A tabela traz a faixa da escala provincial de cada província, departamento e estado e a distribuição dos seus hexágonos nas faixas da OMS.` },
	} as const;
	const scaleTxt = $derived(SCALE_TXT[(locale as keyof typeof SCALE_TXT)] ?? SCALE_TXT.es);
	const nf = $derived((v: number) => v.toLocaleString(locale === 'en' ? 'en' : 'es', { minimumFractionDigits: 1, maximumFractionDigits: 1 }));
	const bandHeads = $derived.by(() => {
		const b = data.scaleStats?.bands ?? [];
		if (b.length === 0) return [];
		return [`≤${b[0]}`, ...b.slice(1).map((hi: number, i: number) => `${b[i]}–${hi}`), `>${b[b.length - 1]}`];
	});

	// Stamps the printout, so it must be the reader's date — computed client-side only,
	// since prerendering would otherwise freeze the build date into the HTML.
	const today = browser
		? new Date().toLocaleDateString('es-AR', {
				year: 'numeric',
				month: 'long',
				day: 'numeric',
			})
		: '';

	function handlePrint() {
		if (typeof window !== 'undefined') window.print();
	}
</script>

