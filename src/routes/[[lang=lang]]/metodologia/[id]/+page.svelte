	{/if}

	{#if data.scaleStats && data.regionalColorDomain}
		<section class="section">
			<h2>{scaleTxt.h}</h2>
			<p>{@html scaleTxt.intro(nf(data.regionalColorDomain[0]), nf(data.regionalColorDomain[1]))}</p>
			<div class="scale-table-wrap">
				<table class="scale-table">
					<thead>
						<tr>
							<th rowspan="2">{scaleTxt.terr}</th>
							<th rowspan="2">{scaleTxt.range}</th>
							<th rowspan="2">{scaleTxt.minmax}</th>
							<th colspan={bandHeads.length}>{scaleTxt.bands}</th>
						</tr>
						<tr>{#each bandHeads as h}<th>{h}</th>{/each}</tr>
					</thead>
					<tbody>
						{#each Object.values(data.scaleStats.territories) as t}
							<tr>
								<td>{t.label} ({t.country.toUpperCase()})</td>
								<td>{nf(t.p2)}–{nf(t.p98)}</td>
								<td>{nf(t.min)}–{nf(t.max)}</td>
								{#each t.bandsPct as p}<td class:zero={p === 0}>{nf(p)}</td>{/each}
							</tr>
						{/each}
					</tbody>
				</table>
			</div>
			<p class="note">ACAG V6, 2013–2022 · {data.scaleStats.generated}</p>
		</section>
	{/if}

	<section class="section">
		<h2>{i18n.t('section.downloads')}</h2>
		<p class="note">
			{@html i18n.t('page.metodologia.downloadsText')}
		</p>
	</section>

	<footer class="footer">
		<p>
			{i18n.t('section.citation')}: Gomez, R. E. (2026). Spatia: A Reproducible Platform for Subnational Geospatial Analysis. Zenodo. <a href="https://doi.org/10.5281/zenodo.19483040">https://doi.org/10.5281/zenodo.19483040</a>
		</p>
		<p class="affil">CONICET · FHyCS-UNaM · Google Earth Engine Partner Tier</p>
