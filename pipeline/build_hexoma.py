# ── database setup ────────────────────────────────────────────────────────────

def connect(db: str):
    conn = psycopg2.connect(f'{PG}/{db}')
    conn.set_client_encoding('UTF8')
    return conn


def ensure_database() -> None:
    conn = connect('postgres')
    conn.autocommit = True
    with conn.cursor() as cur:
        cur.execute('SELECT 1 FROM pg_database WHERE datname = %s', (DB,))
        if not cur.fetchone():
            cur.execute(sql.SQL('CREATE DATABASE {} ENCODING {} TEMPLATE template0').format(
                sql.Identifier(DB), sql.Literal('UTF8')))
            log(f'created database {DB}')
    conn.close()


