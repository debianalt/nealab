"""Hexoma — load every Spatia layer, per H3 res-9 hexagon, into the local Postgres
database `hexoma` (private research base; never published, nothing goes to R2).

The Hexoma of a cell is its full vector: every layer, every scale, every time slice.
This script reads the SAME parquets the hexagon fact sheet reads
(src/lib/utils/ficha.ts: per-department files via the dept summaries' parquetKey,
territory-wide only for non-perDepartment layers such as censo_temporal), so a value
in `v_hexoma` matches the fact sheet and the layer panel: shown value = (rawCol ?? col)
× scale. The list of files, columns, units and labels comes from the web app itself
through pipeline/hexoma_registry.mjs (Vite SSR over config.ts), not from a copy.

Idempotent: each (layer, territory) is deleted and reloaded in one transaction.
Regenerable from R2 at any time, so the base has no backup of its own.

Usage (from neahub/):
    python pipeline/build_hexoma.py                       # NEA AR, all layers
    python pipeline/build_hexoma.py --territories misiones --layers land_use
    python pipeline/build_hexoma.py --skip-registry       # reuse output/hexoma/registry.json

Env: HEXOMA_PG (default postgresql://postgres@localhost:5432) — server, no db name.
"""
